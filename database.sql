-- Im Supabase SQL Editor als Projektbesitzer ausführen.
create table if not exists public.song_requests (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 40),
  song text not null check (char_length(song) between 1 and 120),
  message text not null default '' check (char_length(message) <= 400),
  created_at timestamptz not null default now()
);

alter table public.song_requests enable row level security;

-- Besucher dürfen Songwünsche absenden, aber nicht lesen oder ändern.
create policy "Anyone can submit song requests"
on public.song_requests for insert
to anon, authenticated
with check (
  char_length(trim(name)) between 1 and 40
  and char_length(trim(song)) between 1 and 120
  and char_length(message) <= 400
);

-- Nur angemeldete Admins dürfen Wünsche sehen und löschen.
create policy "Admins can read song requests"
on public.song_requests for select
to authenticated
using (true);

create policy "Admins can delete song requests"
on public.song_requests for delete
to authenticated
using (true);

-- Realtime für neue Einträge einschalten.
alter publication supabase_realtime add table public.song_requests;